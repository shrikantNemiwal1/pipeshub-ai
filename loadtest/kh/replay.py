Transform = Callable[[str], str]


def sub(old: str, new: str, *, count: int = 1, label: str = "") -> Transform:
    """A text replacement that fails loudly when it does not apply."""

    def apply(query: str) -> str:
        if query.count(old) < count:
            raise AssertionError(
                f"transform {label!r} did not match (wanted {count}, "
                f"found {query.count(old)}): {old[:90]!r}"
            )
        return query.replace(old, new, count)

    return apply


def chain(*transforms: Transform) -> Transform:
    def apply(query: str) -> str:
        for t in transforms:
            query = t(query)
        return query

    return apply


