"""Capture the real connector-page query once, then replay variants of it.

The baseline is generated BY THE PROVIDER, never hand-copied: `capture()`
monkeypatches `Neo4jClient.execute_query` and calls
`get_knowledge_hub_connector_page_v3` for real. That is what stops the arms
drifting from shipped code the way `docs/kh-v3/*.cypher` already did.

Each arm is a text transform over that baseline. Every transform asserts it
actually matched -- a silently-inapplicable edit would otherwise produce a
"1.0x, no effect" result that looks like a finding.

Two rules enforced here:
  * a PROFILEd run is never a timing sample (profiling forces materialisation);
  * an arm whose returned page differs from the control is reported as BROKEN,
    never as a speedup.
"""

