def _arm_kill(var: str, start_marker: str, end_marker: str, label: str) -> Transform:
    """Replace a whole scope arm with an empty list for its output variable."""

    def apply(query: str) -> str:
        i = query.find(start_marker)
        if i < 0:
            raise AssertionError(f"{label}: start marker not found")
        j = query.find(end_marker, i)
        if j < 0:
            raise AssertionError(f"{label}: end marker not found")
        return query[:i] + end_marker + query[j + len(end_marker):]

    return apply


def block(start_marker: str, end_marker: str, replacement: str,
          *, label: str) -> Transform:
    """Replace a whole block, from the line holding `start_marker` through the
    line holding `end_marker`, with `replacement`.

    Arm kills keep the arm's output variable in scope (bound to `[]`) so every
    downstream clause still parses and still pays its own cost.
    """

    def apply(query: str) -> str:
        lines = query.splitlines()
        starts = [i for i, ln in enumerate(lines) if start_marker in ln]
        if not starts:
            raise AssertionError(f"{label}: start marker not found: {start_marker!r}")
        i = starts[0]
        ends = [j for j, ln in enumerate(lines) if j >= i and end_marker in ln]
        if not ends:
            raise AssertionError(f"{label}: end marker not found: {end_marker!r}")
        j = ends[0]
        return chr(10).join(lines[:i] + [replacement] + lines[j + 1:])

    return apply


